(* [embed FILE..] prints an OCaml module with the contents of the files:
     let files = [ (basename, contents); .. ]
   so that an executable carries its Elpi files (elpi-check, elpi-debug);
   [file name] is the contents of the file whose basename is name. *)

let read file = In_channel.with_open_bin file In_channel.input_all

let () =
  print_endline "(* Generated by embed.ml: Elpi files embedded in an executable *)";
  print_endline "let files = [";
  Array.iteri
    (fun i file ->
      if i > 0 then Printf.printf "  (%S, %S);\n" (Filename.basename file) (read file))
    Sys.argv;
  print_endline "]";
  print_endline "let file name = List.assoc name files"
